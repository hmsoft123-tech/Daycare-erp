export function getLetterTemplate(kind: LetterKind): LetterTemplate | undefined {
  return LETTER_TEMPLATES.find((t) => t.kind === kind);
}

export function fillTemplate(text: string, values: Record<string, string>): string {
  return text.replace(/\{\{(\w+)\}\}/g, (_, key: string) => values[key]?.trim() || "________");
}

